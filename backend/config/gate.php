<?php

return [

    /*
    |--------------------------------------------------------------------------
    | 入場閘門
    |--------------------------------------------------------------------------
    |
    | 在扣 activities.joined_count 之前，先讓 Redis 擋掉「必定會失敗」的請求。
    |
    | 這一層是削峰用的，不是保證正確用的。正確性仍然完全在 MySQL 的條件式
    | UPDATE ... WHERE joined_count < capacity —— 閘門就算完全失效（Redis 掛掉、
    | 資料被清空、數字漂移），也不可能造成超賣。
    |
    */

    'enabled' => (bool) env('GATE_ENABLED', true),

    'connection' => env('GATE_REDIS_CONNECTION', 'gate'),

    /*
    |--------------------------------------------------------------------------
    | 閘門的存活時間（秒）
    |--------------------------------------------------------------------------
    |
    | 閘門是「用完可以丟掉」的東西。它在第一個請求抵達時從資料庫建起來，過期之後
    | 下一個請求會再建一次 —— 而重建讀的是 MySQL，也就是每次重建都自動對帳一次。
    |
    | 所以這個值是在調「多久強制回頭看一次真相」，不是在調快取效期。設短一點，
    | 漂移的存活時間就短；設長一點，資料庫的讀取就少。六小時足以覆蓋一場開賣，
    | 而遠在三個月後的活動不需要一直佔著記憶體。
    |
    */

    'ttl' => (int) env('GATE_TTL', 6 * 60 * 60),

];
